// Optional authoring step on macOS. Committed audio works on every target platform.
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdir, stat, writeFile, rm, mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { allSpeech } from '../dist/games/tiny-wonderland/speech.js';
const run = promisify(execFile);
const root = fileURLToPath(new URL('../dist/games/tiny-wonderland/',import.meta.url));
const directory = path.join(root,'assets/audio');
await mkdir(directory,{ recursive:true });
const temp = await mkdtemp(path.join(tmpdir(),'wonderland-voice-'));
const entries = [...allSpeech()], manifest = {};
let cursor = 0, completed = 0;
try {
  await Promise.all(Array.from({length:3}, async () => {
    while (cursor < entries.length) {
      const [key,clip] = entries[cursor++], name = `${clip.language}-${key}.m4a`, output = path.join(directory,name);
      const existing = await stat(output).catch(() => null);
      if (!existing || existing.size < 700) {
        const source = path.join(temp,`${key}.aiff`);
        await run('/usr/bin/say',['-v',clip.language === 'en' ? 'Samantha' : 'Tingting','-r',clip.language === 'en' ? '140' : '155','-o',source,clip.text]);
        if ((await stat(source)).size <= 4096) throw new Error(`Empty speech output for ${clip.text}; local speech service permission is required.`);
        await run('/usr/bin/afconvert',['-f','m4af','-d','aac','-b','48000',source,output]);
        await rm(source);
      }
      manifest[key] = name;
      completed++;
      if (completed % 40 === 0) console.log(`${completed}/${entries.length} clips ready`);
    }
  }));
  const sorted = Object.fromEntries(Object.entries(manifest).sort(([a],[b])=>a.localeCompare(b)));
  await writeFile(path.join(root,'audio-map.js'),'// Generated by scripts/generate-wonderland-audio.mjs.\nexport const audioFiles = '+JSON.stringify(sorted,null,2)+';\n');
  console.log(`Created ${completed} Mandarin / English offline narration clips.`);
} finally { await rm(temp,{recursive:true,force:true}); }
